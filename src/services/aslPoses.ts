/**
 * Returns landmarks for a given letter or phrase token.
 */
export function getLandmarksForToken(token: string): NormalizedLandmark[] {
  if (!token) return REST_POSE;
  const upper = token.trim().toUpperCase();

  if (ASL_LETTER_POSES[upper]) {
    return ASL_LETTER_POSES[upper];
  }

  if (ASL_PHRASE_POSES[upper]) {
    return ASL_PHRASE_POSES[upper];
  }

  // If first char matches A..Z
  const first = upper.charAt(0);
  if (ASL_LETTER_POSES[first]) {
    return ASL_LETTER_POSES[first];
  }

  return REST_POSE;
}
