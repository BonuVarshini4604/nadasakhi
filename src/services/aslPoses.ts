/**
 * Creates 21 3D NormalizedLandmark points from base palm coordinates
 * and fingertip posture configuration.
 */
function buildPose(config: {
  // Wrist position
  wrist?: [number, number, number];
  // Thumb 1..4: [cmc, mcp, ip, tip]
  thumb: [number, number, number][];
  // Index 5..8: [mcp, pip, dip, tip]
  index: [number, number, number][];
  // Middle 9..12: [mcp, pip, dip, tip]
  middle: [number, number, number][];
  // Ring 13..16: [mcp, pip, dip, tip]
  ring: [number, number, number][];
  // Pinky 17..20: [mcp, pip, dip, tip]
  pinky: [number, number, number][];
}): NormalizedLandmark[] {
  const wrist = config.wrist || [0.50, 0.82, 0.0];
  const rawPoints = [
    wrist,
    ...config.thumb,
    ...config.index,
    ...config.middle,
    ...config.ring,
    ...config.pinky,
  ];

  return rawPoints.map(([x, y, z]) => ({
    x: Math.round(x * 1000) / 1000,
    y: Math.round(y * 1000) / 1000,
    z: Math.round((z || 0) * 1000) / 1000,
    visibility: 1,
  }));
}

